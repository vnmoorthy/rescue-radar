"""Write docs/deck/embedded.js so the deck shows real numbers even when opened as a local file (file://),
where browsers block fetch(). Run after scripts/export_static.py."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
D = ROOT / "docs" / "data"
data = {"results": json.loads((D / "results.json").read_text()),
        "replay": json.loads((D / "replay" / "hurricane_dorian_2019.json").read_text()),
        "meta": json.loads((D / "meta.json").read_text())}
out = ROOT / "docs" / "deck" / "embedded.js"
out.write_text("/* Generated by scripts/embed_deck_data.py from docs/data. Do not edit. */\nwindow.RR_EMBED = "
               + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")
